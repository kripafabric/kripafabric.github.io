// Initialize on DOM load
document.addEventListener('DOMContentLoaded', () => {
  // Check URL params (?lang=hi or ?lang=en)
  const urlParams = new URLSearchParams(window.location.search);
  const paramLang = urlParams.get('lang');

  // Check URL hash (#hi or #hindi)
  const hash = window.location.hash.toLowerCase();
  const isHashHindi = (hash === '#hi' || hash === '#hindi');

  // Check localStorage
  let savedLang = null;
  try {
    savedLang = localStorage.getItem('kripa_lang');
  } catch (e) {}

  const initialLang = paramLang || (isHashHindi ? 'hi' : null) || savedLang || 'en';
  setLanguage(initialLang);
});
