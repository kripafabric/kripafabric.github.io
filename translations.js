// Current active language: default 'en'
let currentLang = 'en';

/**
 * Switch website language to 'en' or 'hi'
 * @param {string} lang 
 */
function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'hi') lang = 'en';
  currentLang = lang;
  
  const dict = translations[lang];
  if (!dict) return;

  // 1. Update document html lang
  document.documentElement.lang = lang;

  // 2. Update all elements with data-i18n (textContent)
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  // 3. Update all elements with data-i18n-html (innerHTML for markup)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  // 4. Update elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] !== undefined) {
      el.placeholder = dict[key];
    }
  });

  // 5. Update elements with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key] !== undefined) {
      el.title = dict[key];
    }
  });

  // 6. Update Language Converter Button Labels (Prompt to switch to the other lang)
  // When active is 'en', buttons show 'हिन्दी' (click to switch to Hindi)
  // When active is 'hi', buttons show 'English' (click to switch to English)
  document.querySelectorAll('.lang-btn-text').forEach(el => {
    el.textContent = dict.langBtnLabel;
  });

  document.querySelectorAll('.lang-btn-tooltip').forEach(el => {
    el.setAttribute('title', dict.langTooltip);
    el.setAttribute('aria-label', dict.langTooltip);
  });

  // 7. Update Drawer language toggle pills if present
  const drawerLangEn = document.getElementById('drawerLangEn');
  const drawerLangHi = document.getElementById('drawerLangHi');
  if (drawerLangEn && drawerLangHi) {
    if (lang === 'en') {
      drawerLangEn.className = "px-2.5 py-1 rounded-md transition-colors bg-brand-maroon text-white";
      drawerLangHi.className = "px-2.5 py-1 rounded-md transition-colors text-brand-charcoal hover:bg-brand-linen";
    } else {
      drawerLangHi.className = "px-2.5 py-1 rounded-md transition-colors bg-brand-maroon text-white";
      drawerLangEn.className = "px-2.5 py-1 rounded-md transition-colors text-brand-charcoal hover:bg-brand-linen";
    }
  }

  // 8. Update Calculator dropdown options
  const calcMeters = document.getElementById('calcMeters');
  if (calcMeters && calcMeters.options.length >= 4) {
    calcMeters.options[0].text = dict.calcOptQty1;
    calcMeters.options[1].text = dict.calcOptQty2;
    calcMeters.options[2].text = dict.calcOptQty3;
    calcMeters.options[3].text = dict.calcOptQty4;
  }

  const calcBuyerType = document.getElementById('calcBuyerType');
  if (calcBuyerType && calcBuyerType.options.length >= 5) {
    calcBuyerType.options[0].text = dict.calcOptBuyer1;
    calcBuyerType.options[1].text = dict.calcOptBuyer2;
    calcBuyerType.options[2].text = dict.calcOptBuyer3;
    calcBuyerType.options[3].text = dict.calcOptBuyer4;
    calcBuyerType.options[4].text = dict.calcOptBuyer5;
  }

  // 9. Update 48 Maal Cards badges and buttons
  document.querySelectorAll('.maal-ready-badge').forEach(el => {
    el.textContent = dict.readyStockBadge;
  });
  document.querySelectorAll('.mandi-rate-text').forEach(el => {
    el.textContent = dict.mandiRateLabel;
  });
  document.querySelectorAll('.todays-rate-btn-text').forEach(el => {
    el.textContent = dict.todaysRateBtn;
  });
  document.querySelectorAll('.meta-packing-label').forEach(el => {
    el.textContent = dict.packingLabel;
  });
  document.querySelectorAll('.meta-suited-label').forEach(el => {
    el.textContent = dict.bestSuitedLabel;
  });

  // Re-run filterMaal count badge to update 'Varieties' / 'किस्में'
  if (typeof filterMaal === 'function') {
    filterMaal();
  }

  // 10. Persist language selection in localStorage
  try {
    localStorage.setItem('kripa_lang', lang);
  } catch (e) {
    // localStorage might be unavailable in some private windows
  }

  // 11. Re-render Lucide icons
  if (window.lucide && typeof lucide.createIcons === 'function') {
    lucide.createIcons();
  }
}

/**
 * Toggle between English and Hindi
 */
function toggleLanguage() {
  const nextLang = (currentLang === 'en') ? 'hi' : 'en';
  setLanguage(nextLang);

  // Optional toast notification
  if (typeof showToast === 'function') {
    if (nextLang === 'hi') {
      showToast('वेबसाइट हिन्दी में परिवर्तित हो गई है');
    } else {
      showToast('Website converted to English');
    }
  }
}

